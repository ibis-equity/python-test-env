from databricks.sdk import WorkspaceClient
from databricks.sdk.errors.platform import PermissionDenied

w = WorkspaceClient()

# Public DBFS root (/) is often disabled; use a Unity Catalog volume or another allowed path.
TARGET_PATH = "/Volumes"

try:
  entries = w.dbutils.fs.ls(TARGET_PATH)
  for f in entries:
    print(f.path)
except PermissionDenied:
  print(
      "Access denied for path '/'. Update TARGET_PATH to an allowed location, "
      "for example: /Volumes/<catalog>/<schema>/<volume>/"
  )













































































































































